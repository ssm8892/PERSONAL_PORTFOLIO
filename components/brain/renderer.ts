/* ==========================================================================
   Brain renderer — Canvas 2D.

   Geometry comes from public/brain.json (generated by scripts/generate-brain.mjs).

   Everything static is pre-rendered once per resize into offscreen layers:
     baseL / baseR   dim line-art of each hemisphere (+ its off-screen extensions)
     devLit          left hemisphere lit up: glowing circuit traces, vias, PCB dots
     artLit          right hemisphere lit up: watercolor blooms, painted folds, ink
   Each frame only composites those layers and draws the few things that move:
     - a reveal that spreads the lit layer outward from the cursor (spring-driven)
     - a spotlight that brightens detail right under the cursor
     - signal pulses travelling along the circuit traces (developer side)
     - a fading brush trail that follows the cursor (artist side)
   ========================================================================== */

import { Spring } from "@/lib/spring";

export type BrainData = {
  W: number;
  H: number;
  left: { outline: number[]; traces: number[][]; vias: number[] };
  right: { outline: number[]; folds: number[][] };
  dev: { bus: number[][] };
  art: { strokes: { w: number; c: number; p: number[] }[]; drops: number[] };
};

export type Side = "left" | "right" | "none";

export type BrainLayout = { leftX: number; rightX: number; centerY: number; width: number; height: number };

type Options = {
  reduceMotion: boolean;
  onLayout?: (l: BrainLayout) => void;
  onParallax?: (x: number, y: number) => void;
};

const DEV = "#2997ff";
const DEV_CORE = "#cfe6ff";
const PALETTE = ["#feca57", "#ff9f43", "#ff6b6b", "#f368e0", "#a55eea", "#ff7f50"];
const PAD = 32; // CSS px of overdraw around the viewport so parallax never shows an edge

/* ---------- small geometry helpers (cell units) ---------- */

const unpack = (a: number[]) => {
  const out = new Float32Array(a.length);
  for (let i = 0; i < a.length; i++) out[i] = a[i] / 10;
  return out;
};

function polyPath(p: Float32Array, closed = false) {
  const path = new Path2D();
  path.moveTo(p[0], p[1]);
  for (let i = 2; i < p.length; i += 2) path.lineTo(p[i], p[i + 1]);
  if (closed) path.closePath();
  return path;
}

/** Smooth curve through points (quadratic segments via midpoints). */
function smoothPath(p: Float32Array, closed = false) {
  const path = new Path2D();
  const n = p.length / 2;
  if (n < 3) return polyPath(p, closed);
  path.moveTo(p[0], p[1]);
  for (let i = 1; i < n - 1; i++) {
    const x = p[i * 2], y = p[i * 2 + 1];
    const mx = (x + p[i * 2 + 2]) / 2, my = (y + p[i * 2 + 3]) / 2;
    path.quadraticCurveTo(x, y, mx, my);
  }
  path.lineTo(p[(n - 1) * 2], p[(n - 1) * 2 + 1]);
  if (closed) path.closePath();
  return path;
}

/** Densify with Catmull-Rom so tapered strokes have enough samples to curve. */
function catmull(p: Float32Array, perSeg = 8) {
  const n = p.length / 2;
  const out: number[] = [];
  const P = (i: number) => {
    const k = Math.max(0, Math.min(n - 1, i));
    return [p[k * 2], p[k * 2 + 1]];
  };
  for (let i = 0; i < n - 1; i++) {
    const [x0, y0] = P(i - 1), [x1, y1] = P(i), [x2, y2] = P(i + 1), [x3, y3] = P(i + 2);
    for (let s = 0; s < perSeg; s++) {
      const t = s / perSeg, t2 = t * t, t3 = t2 * t;
      out.push(
        0.5 * (2 * x1 + (-x0 + x2) * t + (2 * x0 - 5 * x1 + 4 * x2 - x3) * t2 + (-x0 + 3 * x1 - 3 * x2 + x3) * t3),
        0.5 * (2 * y1 + (-y0 + y2) * t + (2 * y0 - 5 * y1 + 4 * y2 - y3) * t2 + (-y0 + 3 * y1 - 3 * y2 + y3) * t3)
      );
    }
  }
  out.push(p[(n - 1) * 2], p[(n - 1) * 2 + 1]);
  return out;
}

/** Filled brush stroke whose width swells and tapers along its length. */
function taperedStroke(pts: number[], width: number) {
  const n = pts.length / 2;
  const left: number[] = [], right: number[] = [];
  for (let i = 0; i < n; i++) {
    const a = Math.max(0, i - 1), b = Math.min(n - 1, i + 1);
    let tx = pts[b * 2] - pts[a * 2], ty = pts[b * 2 + 1] - pts[a * 2 + 1];
    const len = Math.hypot(tx, ty) || 1;
    tx /= len; ty /= len;
    const t = i / (n - 1);
    const w = (width / 2) * Math.pow(Math.sin(Math.PI * Math.min(1, t * 1.15)), 0.7) * (1 - 0.55 * t);
    left.push(pts[i * 2] - ty * w, pts[i * 2 + 1] + tx * w);
    right.push(pts[i * 2] + ty * w, pts[i * 2 + 1] - tx * w);
  }
  const path = new Path2D();
  path.moveTo(left[0], left[1]);
  for (let i = 2; i < left.length; i += 2) path.lineTo(left[i], left[i + 1]);
  for (let i = right.length - 2; i >= 0; i -= 2) path.lineTo(right[i], right[i + 1]);
  path.closePath();
  return path;
}

function mulberry32(seed: number) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* ---------- pulse paths (arc-length parameterised) ---------- */

type Track = { p: Float32Array; cum: Float32Array; len: number };

function track(p: Float32Array): Track {
  const n = p.length / 2;
  const cum = new Float32Array(n);
  for (let i = 1; i < n; i++) cum[i] = cum[i - 1] + Math.hypot(p[i * 2] - p[i * 2 - 2], p[i * 2 + 1] - p[i * 2 - 1]);
  return { p, cum, len: cum[n - 1] };
}

function pointAt(t: Track, s: number, out: { x: number; y: number }) {
  const { p, cum } = t;
  let lo = 0, hi = cum.length - 1;
  while (lo < hi - 1) {
    const mid = (lo + hi) >> 1;
    if (cum[mid] < s) lo = mid; else hi = mid;
  }
  const seg = cum[hi] - cum[lo] || 1;
  const k = Math.max(0, Math.min(1, (s - cum[lo]) / seg));
  out.x = p[lo * 2] + (p[hi * 2] - p[lo * 2]) * k;
  out.y = p[lo * 2 + 1] + (p[hi * 2 + 1] - p[lo * 2 + 1]) * k;
}

type Pulse = { t: Track; s: number; speed: number; trail: number };
type TrailPoint = { x: number; y: number; t: number; c: number };

/* ========================================================================== */

export class BrainRenderer {
  private canvas: HTMLCanvasElement;
  private ctx: CanvasRenderingContext2D;
  private opts: Options;

  // geometry (cell units)
  private W: number;
  private H: number;
  private outlineL: Float32Array;
  private outlineR: Float32Array;
  private traces: Float32Array[];
  private vias: Float32Array;
  private folds: Float32Array[];
  private bus: Float32Array[];
  private strokes: { w: number; c: number; p: Float32Array }[];
  private drops: Float32Array;
  private tracks: Track[];

  // layout (CSS px)
  private vw = 0;
  private vh = 0;
  private dpr = 1;
  private s = 1;   // px per cell
  private ox = 0;  // brain origin
  private oy = 0;

  // layers
  private baseL!: HTMLCanvasElement;
  private baseR!: HTMLCanvasElement;
  private devLit!: HTMLCanvasElement;
  private artLit!: HTMLCanvasElement;
  private temp!: HTMLCanvasElement;
  private spot!: HTMLCanvasElement;

  // state
  private active: Side = "none";
  private levelL = new Spring({ response: 0.8, damping: 1 });
  private levelR = new Spring({ response: 0.8, damping: 1 });
  private intro = new Spring({ value: 0, response: 1.4, damping: 1 });
  private parX = new Spring({ response: 0.9, damping: 1 });
  private parY = new Spring({ response: 0.9, damping: 1 });
  private centerL = { x: 0, y: 0 };
  private centerR = { x: 0, y: 0 };
  private pointer = { x: -1, y: -1, inside: false };
  private pulses: Pulse[] = [];
  private trail: TrailPoint[] = [];
  private trailColor = 0;
  private raf = 0;
  private last = 0;
  private running = false;
  private tmp = { x: 0, y: 0 };

  constructor(canvas: HTMLCanvasElement, data: BrainData, opts: Options) {
    this.canvas = canvas;
    this.ctx = canvas.getContext("2d")!;
    this.opts = opts;

    this.W = data.W;
    this.H = data.H;
    this.outlineL = unpack(data.left.outline);
    this.outlineR = unpack(data.right.outline);
    this.traces = data.left.traces.map(unpack);
    this.vias = unpack(data.left.vias);
    this.folds = data.right.folds.map(unpack);
    this.bus = data.dev.bus.map(unpack);
    this.strokes = data.art.strokes.map((s) => ({ w: s.w, c: s.c, p: unpack(s.p) }));
    this.drops = unpack(data.art.drops);
    this.tracks = [...this.traces.map(track), ...this.bus.map(track)];

    const rnd = mulberry32(7);
    const count = opts.reduceMotion ? 0 : 150;
    for (let i = 0; i < count; i++) this.pulses.push(this.spawn(rnd(), true));

    this.resize();
    this.intro.target = 1;
    if (opts.reduceMotion) this.intro.snap(1);
  }

  /* ---------- public API ---------- */

  start() {
    if (this.running) return;
    this.running = true;
    this.last = 0;
    this.raf = requestAnimationFrame(this.frame);
  }

  stop() {
    this.running = false;
    cancelAnimationFrame(this.raf);
  }

  destroy() {
    this.stop();
    // Release the big bitmaps right away
    for (const c of [this.baseL, this.baseR, this.devLit, this.artLit, this.temp, this.spot]) {
      if (c) { c.width = 0; c.height = 0; }
    }
  }

  setActive(side: Side) {
    if (side === this.active) return;
    this.active = side;
    const grow = (s: Spring) => { s.configure(0.8, 1); s.target = 1; };
    const shrink = (s: Spring) => { s.configure(0.45, 1); s.target = 0; };
    const p = this.pointer.x >= 0 ? this.pointer : { x: this.vw / 2, y: this.vh / 2 };
    // Spread from where the cursor is — unless the side is still partly lit, then keep its origin.
    if (side === "left") {
      if (this.levelL.value < 0.05) this.centerL = { x: p.x, y: p.y };
      grow(this.levelL); shrink(this.levelR);
    } else if (side === "right") {
      if (this.levelR.value < 0.05) this.centerR = { x: p.x, y: p.y };
      grow(this.levelR); shrink(this.levelL);
    } else {
      shrink(this.levelL); shrink(this.levelR);
    }
    if (this.opts.reduceMotion) {
      this.levelL.snap(this.levelL.target);
      this.levelR.snap(this.levelR.target);
    }
  }

  setPointer(x: number, y: number, inside = true) {
    const moved = Math.hypot(x - this.pointer.x, y - this.pointer.y);
    this.pointer = { x, y, inside };
    if (!inside) {
      this.parX.target = 0;
      this.parY.target = 0;
      return;
    }
    if (!this.opts.reduceMotion) {
      // The brain leans gently toward the cursor (decorative → spring, critically damped)
      this.parX.target = ((x / this.vw) * 2 - 1) * 14;
      this.parY.target = ((y / this.vh) * 2 - 1) * 9;
      if (this.active === "right" && moved > 2) {
        this.trail.push({ x, y, t: performance.now(), c: this.trailColor });
        this.trailColor = (this.trailColor + 0.02) % PALETTE.length;
        if (this.trail.length > 90) this.trail.shift();
      }
    }
  }

  resize() {
    const vw = window.innerWidth;
    const vh = window.innerHeight;
    // Cap the backing-store density: these layers are full-screen bitmaps.
    this.dpr = Math.min(window.devicePixelRatio || 1, 1.5);
    this.vw = vw;
    this.vh = vh;
    this.canvas.width = Math.round(vw * this.dpr);
    this.canvas.height = Math.round(vh * this.dpr);

    // Brain fills most of the screen: up to 86% of the height (leaving room for the name
    // above it). On portrait phones it bleeds a little past the sides to use the height.
    const aspect = this.W / this.H;
    const widthFill = vw < vh ? 1.18 : 0.96;
    const h = Math.min(vh * 0.86, (vw * widthFill) / aspect);
    this.s = h / this.H;
    this.ox = vw / 2 - (this.W * this.s) / 2;
    this.oy = Math.max(vh / 2 - h / 2 + vh * 0.035, 84);

    this.opts.onLayout?.({
      leftX: this.ox + this.W * this.s * 0.25,
      rightX: this.ox + this.W * this.s * 0.75,
      centerY: this.oy + h * 0.5,
      width: this.W * this.s,
      height: h,
    });

    this.buildLayers();
    if (!this.running) this.draw(performance.now());
  }

  /* ---------- layer construction ---------- */

  private layer() {
    const c = document.createElement("canvas");
    c.width = Math.round((this.vw + PAD * 2) * this.dpr);
    c.height = Math.round((this.vh + PAD * 2) * this.dpr);
    const ctx = c.getContext("2d")!;
    // Draw in brain cell units.
    const k = this.dpr * this.s;
    ctx.setTransform(k, 0, 0, k, this.dpr * (this.ox + PAD), this.dpr * (this.oy + PAD));
    ctx.lineCap = "round";
    ctx.lineJoin = "round";
    return { c, ctx };
  }

  /** CSS px → cell units for line widths */
  private px(n: number) {
    return n / this.s;
  }

  private buildLayers() {
    const outlineL = smoothPath(this.outlineL, true);
    const outlineR = smoothPath(this.outlineR, true);

    /* ----- dim base, left ----- */
    {
      const { c, ctx } = this.layer();
      ctx.strokeStyle = "rgba(160, 190, 230, 0.07)";
      ctx.lineWidth = this.px(1);
      for (const b of this.bus) ctx.stroke(polyPath(b));
      ctx.strokeStyle = "rgba(180, 200, 235, 0.17)";
      ctx.lineWidth = this.px(1);
      for (const t of this.traces) ctx.stroke(polyPath(t));
      ctx.strokeStyle = "rgba(220, 230, 255, 0.26)";
      ctx.lineWidth = this.px(1.25);
      ctx.stroke(outlineL);
      this.baseL = c;
    }

    /* ----- dim base, right ----- */
    {
      const { c, ctx } = this.layer();
      ctx.fillStyle = "rgba(255, 210, 190, 0.06)";
      for (const s of this.strokes) ctx.fill(taperedStroke(catmull(s.p), s.w * 0.5));
      ctx.strokeStyle = "rgba(255, 225, 210, 0.17)";
      ctx.lineWidth = this.px(1);
      for (const f of this.folds) ctx.stroke(smoothPath(f));
      ctx.strokeStyle = "rgba(255, 235, 225, 0.26)";
      ctx.lineWidth = this.px(1.25);
      ctx.stroke(outlineR);
      this.baseR = c;
    }

    /* ----- developer, lit ----- */
    {
      const { c, ctx } = this.layer();
      const rnd = mulberry32(11);

      // Hemisphere tint + PCB dot grid
      const g = ctx.createRadialGradient(this.W * 0.3, this.H * 0.5, 0, this.W * 0.3, this.H * 0.5, this.H * 0.6);
      g.addColorStop(0, "rgba(41, 151, 255, 0.16)");
      g.addColorStop(1, "rgba(41, 151, 255, 0.02)");
      ctx.fillStyle = g;
      ctx.fill(outlineL);
      ctx.save();
      ctx.clip(outlineL);
      ctx.fillStyle = "rgba(120, 180, 255, 0.22)";
      const step = 5;
      const r = this.px(0.7);
      for (let y = 0; y < this.H; y += step) for (let x = 0; x < this.W / 2; x += step) ctx.fillRect(x - r, y - r, r * 2, r * 2);
      ctx.restore();

      // Glowing traces: a soft halo pass then a bright core pass
      ctx.shadowColor = DEV;
      ctx.shadowBlur = 10 * this.dpr;
      ctx.strokeStyle = "rgba(64, 160, 255, 0.85)";
      ctx.lineWidth = this.px(1.8);
      for (const t of this.traces) ctx.stroke(polyPath(t));
      ctx.lineWidth = this.px(1.4);
      ctx.strokeStyle = "rgba(64, 160, 255, 0.55)";
      for (const b of this.bus) ctx.stroke(polyPath(b));
      ctx.shadowBlur = 0;
      ctx.strokeStyle = DEV_CORE;
      ctx.globalAlpha = 0.75;
      ctx.lineWidth = this.px(0.6);
      for (const t of this.traces) ctx.stroke(polyPath(t));
      ctx.globalAlpha = 1;

      // Vias: ringed pads at trace ends
      ctx.lineWidth = this.px(1.1);
      for (let i = 0; i < this.vias.length; i += 2) {
        const rad = this.px(rnd() < 0.2 ? 3.4 : 2.3);
        ctx.beginPath();
        ctx.arc(this.vias[i], this.vias[i + 1], rad, 0, Math.PI * 2);
        ctx.fillStyle = "#04101f";
        ctx.fill();
        ctx.strokeStyle = "#8cc8ff";
        ctx.stroke();
      }
      // Bus terminals: little square pads where traces leave the brain
      ctx.fillStyle = "rgba(140, 200, 255, 0.9)";
      for (const b of this.bus) {
        const sz = this.px(3.2);
        ctx.fillRect(b[0] - sz / 2, b[1] - sz / 2, sz, sz);
      }

      ctx.shadowColor = DEV;
      ctx.shadowBlur = 14 * this.dpr;
      ctx.strokeStyle = "rgba(120, 190, 255, 0.9)";
      ctx.lineWidth = this.px(1.6);
      ctx.stroke(outlineL);
      this.devLit = c;
    }

    /* ----- artist, lit ----- */
    {
      const { c, ctx } = this.layer();
      const rnd = mulberry32(23);
      const x0 = this.W / 2, x1 = this.W;

      // Watercolor blooms, clipped to the hemisphere
      ctx.save();
      ctx.clip(outlineR);
      ctx.globalCompositeOperation = "lighter";
      for (let i = 0; i < 26; i++) {
        const x = x0 + rnd() * (x1 - x0);
        const y = rnd() * this.H;
        const rad = this.H * (0.08 + rnd() * 0.2);
        const col = PALETTE[Math.floor(rnd() * PALETTE.length)];
        const g = ctx.createRadialGradient(x, y, 0, x, y, rad);
        g.addColorStop(0, col + "38");
        g.addColorStop(0.6, col + "14");
        g.addColorStop(1, col + "00");
        ctx.fillStyle = g;
        ctx.fillRect(x - rad, y - rad, rad * 2, rad * 2);
      }
      ctx.restore();

      // Painted folds: one gradient sweeps warm → cool from front to back of the brain
      const grad = ctx.createLinearGradient(0, 0, 0, this.H);
      grad.addColorStop(0, "#feca57");
      grad.addColorStop(0.3, "#ff9f43");
      grad.addColorStop(0.55, "#ff6b6b");
      grad.addColorStop(0.8, "#f368e0");
      grad.addColorStop(1, "#a55eea");
      ctx.strokeStyle = grad;
      ctx.globalAlpha = 0.35;
      ctx.lineWidth = this.px(4.5);
      for (const f of this.folds) ctx.stroke(smoothPath(f));
      ctx.globalAlpha = 1;
      ctx.shadowColor = "rgba(255, 120, 90, 0.8)";
      ctx.shadowBlur = 8 * this.dpr;
      ctx.lineWidth = this.px(1.7);
      for (const f of this.folds) ctx.stroke(smoothPath(f));
      ctx.shadowBlur = 0;

      // Loose brush strokes sweeping off toward the right edge
      for (const s of this.strokes) {
        const path = taperedStroke(catmull(s.p), s.w);
        ctx.fillStyle = PALETTE[s.c % PALETTE.length];
        ctx.globalAlpha = 0.55;
        ctx.fill(path);
      }
      // Ink splatter
      for (let i = 0; i < this.drops.length; i += 3) {
        ctx.globalAlpha = 0.5 + rnd() * 0.45;
        ctx.fillStyle = PALETTE[Math.floor(rnd() * PALETTE.length)];
        ctx.beginPath();
        ctx.arc(this.drops[i], this.drops[i + 1], this.drops[i + 2], 0, Math.PI * 2);
        ctx.fill();
      }
      ctx.globalAlpha = 1;

      ctx.shadowColor = "rgba(255, 140, 90, 0.9)";
      ctx.shadowBlur = 14 * this.dpr;
      ctx.strokeStyle = "rgba(255, 190, 150, 0.9)";
      ctx.lineWidth = this.px(1.6);
      ctx.stroke(outlineR);
      this.artLit = c;
    }

    this.temp = document.createElement("canvas");
    this.temp.width = this.canvas.width;
    this.temp.height = this.canvas.height;
    this.spot = this.spot || document.createElement("canvas");
  }

  /* ---------- pulses ---------- */

  private spawn(r: number, scatter = false): Pulse {
    // Bias toward hemisphere traces; occasionally run down a bus line to the edge.
    const fromBus = r < 0.12;
    const pool = fromBus ? this.tracks.slice(this.traces.length) : this.tracks.slice(0, this.traces.length);
    const t = pool[Math.floor(Math.random() * pool.length)];
    return {
      t,
      s: scatter ? Math.random() * t.len : 0,
      speed: fromBus ? 90 + Math.random() * 80 : 22 + Math.random() * 40, // cells / s
      trail: fromBus ? 30 : 9 + Math.random() * 8,
    };
  }

  /* ---------- frame ---------- */

  private frame = (now: number) => {
    if (!this.running) return;
    const dt = this.last ? Math.min(0.05, (now - this.last) / 1000) : 1 / 60;
    this.last = now;

    this.levelL.step(dt, 0.001);
    this.levelR.step(dt, 0.001);
    this.intro.step(dt, 0.001);
    this.parX.step(dt);
    this.parY.step(dt);
    this.opts.onParallax?.(this.parX.value, this.parY.value);

    for (const p of this.pulses) {
      p.s += p.speed * dt;
      if (p.s - p.trail > p.t.len) Object.assign(p, this.spawn(Math.random()));
    }

    this.draw(now);
    this.raf = requestAnimationFrame(this.frame);
  };

  private draw(now: number) {
    const ctx = this.ctx;
    const d = this.dpr;
    const W = this.canvas.width, H = this.canvas.height;
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.globalCompositeOperation = "source-over";
    ctx.globalAlpha = 1;
    ctx.clearRect(0, 0, W, H);
    if (!this.baseL) return;

    const offX = (this.parX.value - PAD) * d;
    const offY = (this.parY.value - PAD) * d;
    const L = this.levelL.value;
    const R = this.levelR.value;
    const intro = this.intro.value;
    const diag = Math.hypot(this.vw, this.vh);

    // The brain "boots": its line-art spreads out from the center on first load.
    const center = { x: this.vw / 2, y: this.vh / 2 };
    this.reveal(this.baseL, intro, center, 1 - 0.6 * R, offX, offY, diag * 0.75);
    this.reveal(this.baseR, intro, center, 1 - 0.6 * L, offX, offY, diag * 0.75);

    // A faint idle glow so the neutral state reads as two distinct halves
    const idle = 0.09 * intro;
    if (idle > 0.002) {
      ctx.globalAlpha = idle * (1 - L) * (1 - R);
      ctx.drawImage(this.devLit, offX, offY);
      ctx.drawImage(this.artLit, offX, offY);
      ctx.globalAlpha = 1;
    }

    // The chosen side lights up, spreading from the cursor
    this.reveal(this.devLit, L, this.centerL, 1, offX, offY, diag * 1.15);
    this.reveal(this.artLit, R, this.centerR, 1, offX, offY, diag * 1.15);

    // Spotlight: extra brightness under the cursor on the lit side
    if (this.pointer.inside && !this.opts.reduceMotion) {
      if (L > 0.3) this.spotlight(this.devLit, L, offX, offY);
      if (R > 0.3) this.spotlight(this.artLit, R, offX, offY);
    }

    this.drawPulses(L, intro, offX, offY);
    this.drawTrail(now, R);
  }

  /** Draw `layer` revealed by a soft-edged disc of radius level·maxR around `c` (CSS px). */
  private reveal(layer: HTMLCanvasElement, level: number, c: { x: number; y: number }, alpha: number, offX: number, offY: number, maxR: number) {
    if (level < 0.002 || alpha < 0.002) return;
    const ctx = this.ctx;
    if (level > 0.995 || this.opts.reduceMotion) {
      ctx.globalAlpha = alpha * (this.opts.reduceMotion ? level : 1);
      ctx.drawImage(layer, offX, offY);
      ctx.globalAlpha = 1;
      return;
    }
    const d = this.dpr;
    const t = this.temp.getContext("2d")!;
    t.setTransform(1, 0, 0, 1, 0, 0);
    t.globalCompositeOperation = "source-over";
    t.clearRect(0, 0, this.temp.width, this.temp.height);
    t.drawImage(layer, offX, offY);
    t.globalCompositeOperation = "destination-in";
    const r = Math.max(1, level * maxR * d);
    const g = t.createRadialGradient(c.x * d, c.y * d, r * 0.55, c.x * d, c.y * d, r);
    g.addColorStop(0, "rgba(0,0,0,1)");
    g.addColorStop(1, "rgba(0,0,0,0)");
    t.fillStyle = g;
    t.fillRect(0, 0, this.temp.width, this.temp.height);
    ctx.globalAlpha = alpha * Math.min(1, level * 2.2);
    ctx.drawImage(this.temp, 0, 0);
    ctx.globalAlpha = 1;
  }

  private spotlight(layer: HTMLCanvasElement, level: number, offX: number, offY: number) {
    const d = this.dpr;
    const radius = Math.round(this.H * this.s * 0.2 * d);
    const size = radius * 2;
    if (this.spot.width !== size) { this.spot.width = size; this.spot.height = size; }
    const s = this.spot.getContext("2d")!;
    const cx = this.pointer.x * d, cy = this.pointer.y * d;
    s.globalCompositeOperation = "source-over";
    s.clearRect(0, 0, size, size);
    s.drawImage(layer, offX - (cx - radius), offY - (cy - radius));
    s.globalCompositeOperation = "destination-in";
    const g = s.createRadialGradient(radius, radius, 0, radius, radius, radius);
    g.addColorStop(0, "rgba(0,0,0,1)");
    g.addColorStop(1, "rgba(0,0,0,0)");
    s.fillStyle = g;
    s.fillRect(0, 0, size, size);
    const ctx = this.ctx;
    ctx.globalCompositeOperation = "lighter";
    ctx.globalAlpha = 0.55 * level;
    ctx.drawImage(this.spot, cx - radius, cy - radius);
    ctx.globalAlpha = 1;
    ctx.globalCompositeOperation = "source-over";
  }

  private drawPulses(L: number, intro: number, offX: number, offY: number) {
    if (!this.pulses.length) return;
    const ctx = this.ctx;
    const d = this.dpr;
    const k = this.s * d;
    const bx = offX + (this.ox + PAD) * d;
    const by = offY + (this.oy + PAD) * d;
    // Idle: a few faint signals. Active: the whole hemisphere is busy.
    const visible = Math.round(this.pulses.length * (0.2 + 0.8 * L));
    const alpha = (0.35 + 0.65 * L) * intro;
    if (alpha < 0.01) return;
    ctx.globalCompositeOperation = "lighter";
    const pt = this.tmp;
    for (let i = 0; i < visible; i++) {
      const p = this.pulses[i];
      const segs = 7;
      for (let j = segs; j >= 0; j--) {
        const s = p.s - (j / segs) * p.trail;
        if (s < 0 || s > p.t.len) continue;
        pointAt(p.t, s, pt);
        const x = bx + pt.x * k, y = by + pt.y * k;
        const f = 1 - j / segs;
        ctx.globalAlpha = alpha * f * f;
        ctx.fillStyle = j === 0 ? "#ffffff" : DEV_CORE;
        const r = (j === 0 ? 1.9 : 1.3) * d;
        ctx.beginPath();
        ctx.arc(x, y, r, 0, Math.PI * 2);
        ctx.fill();
      }
    }
    ctx.globalAlpha = 1;
    ctx.globalCompositeOperation = "source-over";
  }

  private drawTrail(now: number, R: number) {
    const life = 900;
    while (this.trail.length && now - this.trail[0].t > life) this.trail.shift();
    if (this.trail.length < 2 || R < 0.05) return;
    const ctx = this.ctx;
    const d = this.dpr;
    // A wet brush: thick and opaque at the tip, thinning and fading as it dries.
    // Segments run through midpoints so the stroke stays one continuous curve.
    ctx.lineCap = "round";
    ctx.lineJoin = "round";
    for (let i = 2; i < this.trail.length; i++) {
      const a = this.trail[i - 2], b = this.trail[i - 1], c = this.trail[i];
      const age = (now - c.t) / life;
      if (age >= 1) continue;
      const f = 1 - age;
      ctx.globalAlpha = 0.85 * f * R;
      ctx.strokeStyle = PALETTE[Math.floor(c.c) % PALETTE.length];
      ctx.lineWidth = (2.5 + 18 * f * f) * d;
      ctx.beginPath();
      ctx.moveTo(((a.x + b.x) / 2) * d, ((a.y + b.y) / 2) * d);
      ctx.quadraticCurveTo(b.x * d, b.y * d, ((b.x + c.x) / 2) * d, ((b.y + c.y) / 2) * d);
      ctx.stroke();
    }
    ctx.globalAlpha = 1;
  }
}
